'safety-org':{L:`
A safety organisation is the arrangement of people, authority and responsibility for safety in a firm.
# Structure (levels)
- <b>Top:</b> board and managing director set policy, budget and accountability.
- <b>Middle:</b> plant and department managers implement plans, inspections and training.
- <b>Lower:</b> supervisors and workers follow safe methods and report hazards.
- Safety department (chief safety officer) advises; safety committees involve workers.
# Types
- <b>Line:</b> safety flows down the chain of command; simple; suits small firms.
- <b>Staff:</b> specialist safety department advises but has no command authority.
- <b>Line and staff:</b> line managers responsible, safety staff advise and audit; most common.
- <b>Committee:</b> joint management–worker committees at plant and department level.
# Importance
- Fixes responsibility at each level; ensures policy and legal compliance.
- Coordinates inspections, training and accident records; builds safety culture.
= Top makes policy, middle makes it happen, bottom makes it work.
@ Top makes Policy, Middle makes it Happen, Bottom makes it Work.`},

